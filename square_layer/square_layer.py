    def CalculateSquarePolygon4326(self):
        haversineDistance = sqrt((self.DesiredLength ** 2) / 2)
        point = (self.CenterPoint.X, self.CenterPoint.Y)

        resNE = inverse_haversine(point, haversineDistance, Direction.NORTHEAST)
        self.UpRightPoint = Vector2D(resNE[1], resNE[0])

        resSE = inverse_haversine(point, haversineDistance, Direction.SOUTHEAST)
        self.DownRightPoint = Vector2D(resSE[1], resSE[0])

        resSW = inverse_haversine(point, haversineDistance, Direction.SOUTHWEST)
        self.DownLeftPoint = Vector2D(resSW[1], resSW[0])

        resNW = inverse_haversine(point, haversineDistance, Direction.NORTHWEST)
        self.UpLeftPoint = Vector2D(resNW[1], resNW[0])

