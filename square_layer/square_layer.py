    def LayDownSquarePolygon(self):
        self.SquarePolygon = QgsGeometry.fromPolygonXY([[QgsPointXY(self.DownLeftPoint.X, self.DownLeftPoint.Y),
                                                         QgsPointXY(self.DownRightPoint.X, self.DownRightPoint.Y),
                                                         QgsPointXY(self.UpRightPoint.X, self.UpRightPoint.Y),
                                                         QgsPointXY(self.UpLeftPoint.X, self.UpLeftPoint.Y)]])

        uri = "polygon?crs=epsg:" + str(self.EPSGToUse) + "&field=id:integer"
        SquareLayer = QgsVectorLayer(uri, "SquarePolygon", "memory")
        QgsProject.instance().addMapLayer(SquareLayer)

