class Vector2D:
    X: 0.0
    Y: 0.0

    def __init__(self, xx, yy):
        self.X = xx
        self.Y = yy


class Polygon2D:

    def __init__(self, topLeft, topRight, bottomLeft, bottomRight):
        self.VerTextA = Vector2D(bottomLeft.X, bottomLeft.Y)
        self.VerTextB = Vector2D(bottomRight.X, bottomRight.Y)
        self.VerTextC = Vector2D(topRight.X, topRight.Y)
        self.VerTextD = Vector2D(topLeft.X, topLeft.Y)


class Utils:
    def My_Range(self, start, end, step):
        while start <= end:
            yield start
            start += step

    def RotatePoint(self, pointToRotate, centerPoint, angleInDegrees):
        angleInRadians = angleInDegrees * (math.pi / 180)
        cosTheta = math.cos(angleInRadians)
        sinTheta = math.sin(angleInRadians)
        return Vector2D(
            (cosTheta * (pointToRotate.X - centerPoint.X) - sinTheta * (
                        pointToRotate.Y - centerPoint.Y) + centerPoint.X),
            (sinTheta * (pointToRotate.X - centerPoint.X) + cosTheta * (
                        pointToRotate.Y - centerPoint.Y) + centerPoint.Y)
        )

    def TextToVector2D(self, text):
        splited = text.split(',')
        return Vector2D(float(splited[0]), float(splited[1]))


class LayerWorks:
    UtilsRef = Utils()

    EPSGToUse = 0

    UpLeftPoint = Vector2D(0, 0)  # 964322.76, 4216672.64
    UpRightPoint = Vector2D(0, 0.)  # 1268515.99, 4162487.05
    DownLeftPoint = Vector2D(0, 0)  # 931870.75, 4013108.27
    DownRightPoint = Vector2D(0, 0)  # 1229529.05, 3959792.95

    DesiredXLength = 0.0
    DesiredYLength = 0.0
    AppliedXLength = 0.0
    AppliedYLength = 0.0

    CalculatedAngleInDegrees = 0
    CalculatedAngleInRadians = 0
    AngleToRotate = 0

    StraightVertices = []
    RotatedVertices = []

    RotatedPolygons = []
    FinalPolygons = []
    BorderPolygon = 0

    BorderLayer = 0

    # def Run(self, upleftpoint, uprightpoint, downleftpoint, downrightpoint, xlength, ylength):
    def Run(self):
        # Clean-up before starting
        self.StraightVertices.clear()
        self.RotatedVertices.clear()
        self.RotatedPolygons.clear()
        self.FinalPolygons.clear()

        # Now go.
        self.DoTrigonometry()
        self.LayStraightVertices()
        self.RotateLaidVertices()
        self.CreatePolygons()
        self.LayDownTheGrid()

    # Put down straight vertices.
    def DoTrigonometry(self):
        # Calculate rotation angle.
        XDiff = self.UpRightPoint.X - self.UpLeftPoint.X
        YDiff = self.UpRightPoint.Y - self.UpLeftPoint.Y
        self.CalculatedAngleInRadians = math.atan2(XDiff, YDiff)
        self.CalculatedAngleInDegrees = self.CalculatedAngleInRadians * (180.0 / math.pi)
        self.AngleToRotate = 90 - self.CalculatedAngleInDegrees

        self.AppliedXLength = self.DesiredXLength
        self.AppliedYLength = self.DesiredYLength

        # self.AppliedXLength = self.DesiredXLength / math.sin(self.CalculatedAngleInRadians)
        # self.AppliedYLength = self.DesiredYLength / math.sin(self.CalculatedAngleInRadians)

    def LayStraightVertices(self):
        for x in Utils.My_Range(self.UtilsRef, self.UpLeftPoint.X, self.UpRightPoint.X, self.AppliedXLength):
            for y in Utils.My_Range(self.UtilsRef, self.DownRightPoint.Y, self.UpLeftPoint.Y, self.AppliedYLength):
                self.StraightVertices.append(Vector2D(x, y))

    def RotateLaidVertices(self):
        for Vertex in self.StraightVertices:
            self.RotatedVertices.append(Utils.RotatePoint(self.UtilsRef, Vertex, self.UpLeftPoint, self.AngleToRotate))

    def CreatePolygons(self):

        # Update border polygon from BorderLayer.
        borderLayer = QgsProject.instance().mapLayersByName("BorderPolygon")[0]

        for feature in borderLayer.getFeatures():
            if feature.geometry().type() == QgsWkbTypes.PolygonGeometry:
                self.BorderPolygon = feature.geometry()

        for Vertex in self.RotatedVertices:
            vertA = Vertex

            unRotatedVertB = Vector2D(vertA.X + self.AppliedXLength, vertA.Y)
            unRotatedVertC = Vector2D(vertA.X + self.AppliedXLength, vertA.Y + self.AppliedYLength)
            unRotatedVertD = Vector2D(vertA.X, vertA.Y + self.AppliedYLength)

            rotatedVertB = Utils.RotatePoint(self.UtilsRef, unRotatedVertB, vertA, self.AngleToRotate)
            rotatedVertC = Utils.RotatePoint(self.UtilsRef, unRotatedVertC, vertA, self.AngleToRotate)
            rotatedVertD = Utils.RotatePoint(self.UtilsRef, unRotatedVertD, vertA, self.AngleToRotate)

            BasicRotatedPolygon = Polygon2D(vertA, rotatedVertB, rotatedVertC, rotatedVertD)
            FinalPolygon = QgsGeometry.fromPolygonXY([[QgsPointXY(vertA.X, vertA.Y),
                                                       QgsPointXY(rotatedVertB.X, rotatedVertB.Y),
                                                       QgsPointXY(rotatedVertC.X, rotatedVertC.Y),
                                                       QgsPointXY(rotatedVertD.X, rotatedVertD.Y)]])

            if (self.BorderPolygon.contains(FinalPolygon)):
                self.RotatedPolygons.append(BasicRotatedPolygon)
                self.FinalPolygons.append(FinalPolygon)

    # Creates a Vector Layer inside the program and then lays down created polygons.
    def LayDownTheGrid(self):
        uri = "polygon?crs=epsg:"+str(self.EPSGToUse)+"&field=id:integer"
        tileLayer = QgsVectorLayer(uri, "TileLayer", "memory")
        QgsProject.instance().addMapLayer(tileLayer)

        for Polygon in self.FinalPolygons:
            fet = QgsFeature()
            fet.setGeometry(Polygon)
            fet.setAttributes([1])
            tileLayer.dataProvider().addFeature(fet)

        tileLayer.updateExtents()
        tileLayer.reload()

        # Put down a border polygon layer.

    def LayDownBorderPolygon(self):
        # Border polygon. This is actually the whole map we're trying to tile-ise.
        self.BorderPolygon = QgsGeometry.fromPolygonXY([[QgsPointXY(self.DownLeftPoint.X, self.DownLeftPoint.Y),
                                                         QgsPointXY(self.DownRightPoint.X, self.DownRightPoint.Y),
                                                         QgsPointXY(self.UpRightPoint.X, self.UpRightPoint.Y),
                                                         QgsPointXY(self.UpLeftPoint.X, self.UpLeftPoint.Y)]])

        uri = "polygon?crs=epsg:"+str(self.EPSGToUse)+"&field=id:integer"
        borderLayer = QgsVectorLayer(uri, "BorderPolygon", "memory")
        QgsProject.instance().addMapLayer(borderLayer)

        fet = QgsFeature()
        fet.setGeometry(self.BorderPolygon)
        fet.setAttributes([1])
        borderLayer.dataProvider().addFeature(fet)

        borderLayer.updateExtents()
        borderLayer.reload()


