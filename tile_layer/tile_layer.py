        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = ':/plugins/tile_layer/icon.png'
        self.add_action(
            icon_path,
            text=self.tr(u'Lay tiles.'),
            callback=self.run,
            parent=self.iface.mainWindow())

